#!/usr/bin/env python3
"""Exactly continue the selected finite high-epsilon CO trajectories to 110 epochs.

The source 40-epoch trajectories are treated as immutable.  Each destination is
prepared by copying its source and then resuming its saved model, optimizer,
scheduler, MEP state, and RNG state at epoch 40.  Apart from output/name/device
and total epoch count, the scientific training recipe is unchanged.
"""
from __future__ import annotations

import argparse
import copy
import csv
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
import fcntl
import hashlib
import json
import math
import os
from pathlib import Path
import shutil
import signal
import subprocess
import sys
import tempfile
import time
from typing import Any

import yaml


ROOT = Path(__file__).resolve().parent
SOURCE_EPOCHS = 40
TARGET_EPOCHS = 110


@dataclass(frozen=True)
class RunSpec:
    epsilon: int
    alpha: int
    lr: float
    source_name: str
    name: str


RUNS = (
    RunSpec(48, 12, 0.03, "trajectory_ours_fd_eps48_alpha12_lr0p03", "full_tuned_ours_fd_eps48_alpha12_lr0p03"),
    RunSpec(64, 16, 0.03, "trajectory_ours_fd_eps64_alpha16_lr0p03", "full_tuned_ours_fd_eps64_alpha16_lr0p03"),
)


def _scientific_config(config: dict[str, Any]) -> dict[str, Any]:
    """Remove only fields allowed to differ between source and continuation."""
    result = copy.deepcopy(config)
    for key in list(result):
        if key.startswith("_") or key in {"name", "device", "output"}:
            result.pop(key)
    result["data"].pop("root", None)
    result["train"].pop("epochs", None)
    return result


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(8 * 1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _load_checkpoint(path: Path) -> dict[str, Any]:
    # All checkpoints are generated by this repository on the user's HPC; do
    # not pass untrusted third-party checkpoint paths to this tool.
    import torch

    return torch.load(path, map_location="cpu", weights_only=False)


def _finite(value: object, label: str) -> float:
    result = float(value)
    if not math.isfinite(result):
        raise ValueError(f"{label}: nonfinite value {value!r}")
    return result


def _read_epochs(path: Path, expected_end_epoch: int) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    required = {
        "epoch", "lr", "train_loss", "train_accuracy", "monitor_clean_accuracy",
        "monitor_pgd10_accuracy", "vact_A", "vact_B", "vact_C", "vact_D", "vact_E",
    }
    if not rows or not required <= set(rows[0]):
        raise ValueError(f"{path}: missing trajectory columns")
    if [int(row["epoch"]) for row in rows] != list(range(expected_end_epoch + 1)):
        raise ValueError(f"{path}: expected exact epochs 0..{expected_end_epoch}")
    for row in rows:
        epoch = row["epoch"]
        for field in required - {"epoch"}:
            _finite(row[field], f"{path}:{epoch}:{field}")
    return rows


def _read_losses(path: Path, expected_end_epoch: int) -> None:
    with path.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    required = {"epoch", "train_ce_loss", "train_logit_mse", "train_feature_mse"}
    if not rows or not required <= set(rows[0]):
        raise ValueError(f"{path}: missing loss columns")
    if [int(row["epoch"]) for row in rows] != list(range(expected_end_epoch + 1)):
        raise ValueError(f"{path}: expected exact epochs 0..{expected_end_epoch}")
    for row in rows:
        for field in required - {"epoch"}:
            _finite(row[field], f"{path}:{row['epoch']}:{field}")


def _check_recipe(config: dict[str, Any], spec: RunSpec, *, target_epochs: int) -> None:
    train = config.get("train", {})
    expected = {
        "objective": "ours_fd", "backend": "mep", "epsilon": spec.epsilon,
        "alpha": spec.alpha, "lr": spec.lr, "mep_logit_weight": 10.0,
        "feature_node": "B", "feature_weight": 200.0, "fd_include_mep_logit": True,
        "monitor_pgd_steps": 10, "monitor_pgd_step_size": spec.epsilon / 4,
        "track_features": True, "abort_on_nonfinite": True,
    }
    for key, value in expected.items():
        if train.get(key) != value:
            raise ValueError(f"recipe mismatch for {spec.name}: train.{key}={train.get(key)!r}, expected {value!r}")
    if int(train.get("epochs", -1)) != target_epochs:
        raise ValueError(f"recipe mismatch for {spec.name}: epochs={train.get('epochs')!r}, expected {target_epochs}")
    if config.get("deterministic") is not True or int(config.get("seed", -1)) != 0:
        raise ValueError(f"recipe mismatch for {spec.name}: expected deterministic seed-0 diagnostic track")


def _source_config(source: Path, spec: RunSpec) -> dict[str, Any]:
    if (source / "nonfinite_diagnostic.json").exists():
        raise ValueError(f"{source}: contains nonfinite diagnostic; refusing continuation")
    config = yaml.safe_load((source / "config.yaml").read_text(encoding="utf-8"))
    if not isinstance(config, dict):
        raise ValueError(f"{source}/config.yaml: invalid YAML mapping")
    _check_recipe(config, spec, target_epochs=SOURCE_EPOCHS)
    return config


def _inspect_run(run: Path, expected: dict[str, Any], *, source: bool) -> tuple[int, bool]:
    if (run / "nonfinite_diagnostic.json").exists():
        raise ValueError(f"{run}: contains nonfinite diagnostic")
    config = yaml.safe_load((run / "config.yaml").read_text(encoding="utf-8"))
    if _scientific_config(config) != _scientific_config(expected):
        raise ValueError(f"{run}/config.yaml: scientific recipe changed")
    checkpoint = _load_checkpoint(run / "resume.pt")
    epoch = int(checkpoint.get("epoch", -1))
    if source and epoch != SOURCE_EPOCHS - 1:
        raise ValueError(f"{run}/resume.pt: expected source epoch {SOURCE_EPOCHS - 1}, got {epoch}")
    if not source and not SOURCE_EPOCHS - 1 <= epoch < TARGET_EPOCHS:
        raise ValueError(f"{run}/resume.pt: expected epoch 39..109, got {epoch}")
    saved_config = checkpoint.get("config")
    if not isinstance(saved_config, dict) or _scientific_config(saved_config) != _scientific_config(expected):
        raise ValueError(f"{run}/resume.pt: scientific recipe changed")
    for name in ("model", "optimizer", "scheduler", "mep", "rng"):
        if checkpoint.get(name) is None:
            raise ValueError(f"{run}/resume.pt: missing {name} state")
    _read_epochs(run / "epochs.csv", epoch)
    _read_losses(run / "loss_components.csv", epoch)
    final = (run / "final.pt").exists() and (run / "final_metrics.json").exists()
    if source and not final:
        raise ValueError(f"{run}: completed 40-epoch source lacks final artifacts")
    if final and epoch != TARGET_EPOCHS - 1 and not source:
        raise ValueError(f"{run}: stale final artifacts before epoch 109")
    return epoch, final and epoch == TARGET_EPOCHS - 1


def _continuation_config(source: dict[str, Any], spec: RunSpec, output_root: Path) -> dict[str, Any]:
    result = copy.deepcopy(source)
    result["name"] = spec.name
    result["device"] = "cuda:0"
    result["data"]["root"] = str(output_root)  # overwritten by the caller with the actual data root
    result["output"]["root"] = str(output_root)
    result["train"]["epochs"] = TARGET_EPOCHS
    return result


def prepare(spec: RunSpec, *, source_root: Path, output_root: Path, data_root: Path) -> tuple[int, bool]:
    source = (source_root / spec.source_name).resolve()
    destination = (output_root / spec.name).resolve()
    if source == destination or source in destination.parents or destination in source.parents:
        raise ValueError("source and destination must be distinct, non-overlapping directories")
    source_config = _source_config(source, spec)
    source_epoch, _ = _inspect_run(source, source_config, source=True)
    continuation = _continuation_config(source_config, spec, output_root)
    continuation["data"]["root"] = str(data_root)

    if destination.exists():
        provenance = json.loads((destination / "continuation.json").read_text(encoding="utf-8"))
        if provenance.get("source") != str(source) or provenance.get("target_epochs") != TARGET_EPOCHS:
            raise ValueError(f"{destination}: belongs to another continuation")
        saved = yaml.safe_load((destination / "continuation_config.yaml").read_text(encoding="utf-8"))
        if saved != continuation:
            raise ValueError(f"{destination}/continuation_config.yaml: differs from requested continuation")
        return _inspect_run(destination, continuation, source=False)

    output_root.mkdir(parents=True, exist_ok=True)
    fingerprints = {name: _sha256(source / name) for name in ("config.yaml", "resume.pt", "best.pt")}
    staging = Path(tempfile.mkdtemp(prefix=f".{spec.name}.preparing-", dir=output_root))
    try:
        shutil.copytree(source, staging, dirs_exist_ok=True)
        # Validate the copied source before archiving its 40-epoch final artifacts.
        # `_inspect_run(..., source=True)` deliberately requires those artifacts.
        _inspect_run(staging, source_config, source=True)
        archive = staging / "source_trajectory"
        archive.mkdir()
        for name in ("config.yaml", "environment.json"):
            shutil.copy2(staging / name, archive / name)
        for name in ("final.pt", "final_metrics.json"):
            (staging / name).rename(archive / name)
        if {name: _sha256(staging / name) for name in fingerprints} != fingerprints:
            raise ValueError(f"{source}: changed while copying; source remains untouched")
        (staging / "continuation_config.yaml").write_text(
            yaml.safe_dump(continuation, sort_keys=False), encoding="utf-8"
        )
        (staging / "continuation.json").write_text(
            json.dumps(
                {
                    "source": str(source), "source_epoch": source_epoch,
                    "target_epochs": TARGET_EPOCHS, "source_sha256": fingerprints,
                    "created_at": datetime.now(timezone.utc).isoformat(),
                    "purpose": "tuned high-epsilon CO diagnostic; not frozen formal baseline",
                }, indent=2, sort_keys=True,
            ) + "\n", encoding="utf-8"
        )
        staging.rename(destination)
    except BaseException:
        print(f"Preparation incomplete; source untouched; inspect retained staging: {staging}", file=sys.stderr)
        raise
    return source_epoch, False


def _stop_process_group(process: subprocess.Popen[Any]) -> None:
    if process.poll() is None:
        try:
            os.killpg(process.pid, signal.SIGTERM)
        except ProcessLookupError:
            pass


def launch(args: argparse.Namespace, states: list[tuple[int, bool]]) -> int:
    pending = [(spec, args.gpus[index]) for index, (spec, (_, complete)) in enumerate(zip(RUNS, states)) if not complete]
    if not pending:
        print("Both 110-epoch continuations are already complete.", flush=True)
        return 0
    logs = args.output_root / "logs"
    logs.mkdir(exist_ok=True)
    processes: list[tuple[RunSpec, subprocess.Popen[Any]]] = []
    try:
        for spec, gpu in pending:
            run = args.output_root / spec.name
            command = [
                sys.executable, "-u", "-m", "co_blessing", "train", "--config", str(run / "continuation_config.yaml"),
                "--resume", str(run / "resume.pt"), "--data-root", str(args.data_root),
                "--output-root", str(args.output_root), "--device", "cuda:0",
            ]
            log = logs / f"{spec.name}.log"
            print(f"launch {spec.name} on physical GPU {gpu}; log={log}", flush=True)
            with log.open("a", encoding="utf-8") as handle:
                process = subprocess.Popen(
                    command, cwd=ROOT, env={**os.environ, "CUDA_VISIBLE_DEVICES": str(gpu)},
                    stdout=handle, stderr=subprocess.STDOUT, start_new_session=True,
                )
            processes.append((spec, process))
        status = 0
        active = list(processes)
        while active:
            for spec, process in active[:]:
                exit_code = process.poll()
                if exit_code is not None:
                    print(f"finish {spec.name}: exit={exit_code}", flush=True)
                    status |= int(exit_code != 0)
                    active.remove((spec, process))
            if active:
                time.sleep(0.5)
        if status:
            return 1
    finally:
        for _, process in processes:
            _stop_process_group(process)
    for spec in RUNS:
        continuation = yaml.safe_load((args.output_root / spec.name / "continuation_config.yaml").read_text(encoding="utf-8"))
        _, complete = _inspect_run(args.output_root / spec.name, continuation, source=False)
        if not complete:
            raise ValueError(f"{spec.name}: exited without a validated epoch-109 final checkpoint")
    print("Both tuned high-epsilon trajectories completed 110 epochs. No Table 2 evaluation was run.", flush=True)
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=Path, default=Path("/data/cjk/FGSM-MEP-cifar10-high-eps-trajectory-screen"))
    parser.add_argument("--output-root", type=Path, default=Path("/data/cjk/FGSM-MEP-cifar10-high-eps-healthy-co-full110"))
    parser.add_argument("--data-root", type=Path, default=Path("/data/cjk/cifar-data"))
    parser.add_argument("--gpus", type=int, nargs="+", default=[0, 1, 2, 3], metavar="GPU")
    parser.add_argument("--prepare-only", action="store_true")
    args = parser.parse_args(argv)
    if not args.gpus or len(set(args.gpus)) != len(args.gpus) or min(args.gpus) < 0:
        parser.error("--gpus requires distinct nonnegative physical GPU IDs")
    if len(args.gpus) < len(RUNS):
        parser.error(f"--gpus requires at least {len(RUNS)} GPU IDs")
    for key in ("source_root", "output_root", "data_root"):
        setattr(args, key, getattr(args, key).expanduser().resolve())
    if args.output_root == args.source_root or args.output_root in args.source_root.parents or args.source_root in args.output_root.parents:
        parser.error("--output-root must be separate from --source-root")
    args.output_root.mkdir(parents=True, exist_ok=True)
    with (args.output_root / ".continuation.lock").open("a", encoding="utf-8") as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            parser.error("another continuation launcher holds this output root")
        states = []
        for spec in RUNS:
            print(f"check/prepare {spec.name}", flush=True)
            epoch, complete = prepare(
                spec, source_root=args.source_root, output_root=args.output_root, data_root=args.data_root
            )
            states.append((epoch, complete))
            print(f"  epoch={epoch}; {'COMPLETE: skip' if complete else 'READY: resume at epoch 40'}", flush=True)
        manifest = {
            "purpose": "tuned high-epsilon CO diagnostic; not frozen formal baseline",
            "source_root": str(args.source_root), "target_epochs": TARGET_EPOCHS,
            "runs": [asdict(spec) for spec in RUNS],
        }
        (args.output_root / "continuation_manifest.json").write_text(
            json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
        )
        if args.prepare_only:
            print("Preparation complete; no GPU jobs launched.", flush=True)
            return 0
        return launch(args, states)


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except KeyboardInterrupt:
        print("Interrupted; source trajectories remain untouched. Re-run to validate and continue.", file=sys.stderr)
        raise SystemExit(130)
    except (OSError, ValueError, KeyError, TypeError, yaml.YAMLError) as error:
        print(f"Cannot continue safely: {error}", file=sys.stderr)
        raise SystemExit(1)
